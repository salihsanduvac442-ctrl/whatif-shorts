import json
L=json.load(open('lines.json')); D=json.load(open('voices/dur.json'))
gap={'l00':.55,'l01':.35,'l09':.15,'l10':.35,'l11':.9,'l12':.3}
t=1.5; out=[]
for l in L:
    if out: t=out[-1]['t1']+gap.get(l['id'],.12)
    out.append({'id':l['id'],'t0':round(t,3),'t1':round(t+D[l['id']],3),'sub':l['sub']})
dur=round(out[-1]['t1']+1.8,2)
open('timeline.js','w').write('// generated by make_timeline.py\nexport const LINES = '+json.dumps(out,indent=1,ensure_ascii=False)+';\nexport const DUR = '+str(dur)+';\n')
for o in out: print(o['id'],o['t0'],o['t1'])
print('DUR',dur)
